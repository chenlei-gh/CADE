#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Install the CADE intent gate as a git hook
==========================================

``.git/hooks`` is not version controlled, so the only durable form of the
installation is a command that can be replayed.  This is that command.

Two hooks are written, both thin wrappers around ``tools/check_intent.py``:

  pre-commit   -- ADVISORY only (always ``--warn-only``).  It runs before the
                  commit message exists, so it cannot see a ``CADE-Intent``
                  trailer.  Blocking here would reject a commit that declares
                  itself perfectly well, so it only prints guidance.
  commit-msg   -- the authoritative gate.  It can read the commit message,
                  which is where the ``CADE-Intent`` trailer lives.

This split is deliberate: a gate that fires before the author has had a
chance to declare is a false block, and false blocks are what make people
turn gates off.

The hook resolves the gate by absolute path and passes ``--workspace``
explicitly.  That matters on Windows: an installed CADE skill may sit in
``~/.agents`` or in a workspace's ``.agents`` shadow copy, and a hook must
not depend on the caller's cwd or PATH.

USAGE
-----
    python tools/check_intent.py --install-hooks --workspace <ws>
    python tools/check_intent.py --install-hooks --workspace <ws> --uninstall
    python tools/check_intent.py --install-hooks --workspace <ws> --warn-only
"""

from __future__ import annotations

import stat
import sys
from pathlib import Path

HOOK_MARKER = "# CADE-INTENT-GATE"

# Resolved from this file's own location, not from __file__ of whatever module
# happens to be executing: this module is the *installer*, and the hook must
# invoke the *gate*. Mixing the two makes the hook exit 0 doing nothing.
GATE_SCRIPT = Path(__file__).resolve().parent / "check_intent.py"

PRE_COMMIT_BODY = """#!/bin/sh
{marker}
# Generated by tools/check_intent.py --install-hooks. Do not edit by hand;
# re-run the installer instead.  Escape hatch: git commit --no-verify
#
# Advisory only: the commit message does not exist yet, so a CADE-Intent
# trailer cannot be seen from here.  commit-msg is the authoritative gate.
# Fail open if the gate has moved (a stale hook must not lock the repository).
[ -f "{gate}" ] || exit 0
exec "{python}" "{gate}" --workspace "{workspace}" --warn-only
"""

COMMIT_MSG_BODY = """#!/bin/sh
{marker}
# Generated by tools/check_intent.py --install-hooks. Do not edit by hand;
# re-run the installer instead.  Escape hatch: git commit --no-verify
# $1 is the commit message file, which is where CADE-Intent trailers live.
#
# Fail open when the gate is gone: a moved checkout or a fresh clone without
# the skill must not turn every commit into a hard error.
if [ ! -f "{gate}" ]; then
    echo "CADE intent gate: not found at {gate}" >&2
    echo "CADE intent gate: allowing this commit (re-run --install-hooks)" >&2
    exit 0
fi
exec "{python}" "{gate}" --workspace "{workspace}" --commit-msg-file "$1"{extra}
"""


def _hooks_dir(workspace: Path) -> Path:
    """Resolve the real hooks directory, honouring core.hooksPath."""
    try:
        import subprocess

        proc = subprocess.run(
            ["git", "-C", str(workspace), "rev-parse", "--git-path", "hooks"],
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=30,
        )
        if proc.returncode == 0 and proc.stdout.strip():
            path = Path(proc.stdout.strip())
            if not path.is_absolute():
                # --git-path reports paths relative to the repository root.
                path = workspace / path
            return path.resolve()
    except (OSError, subprocess.SubprocessError):
        pass
    return workspace / ".git" / "hooks"


def _sh_escape(value: str) -> str:
    """Escape a value for a double-quoted POSIX shell string."""
    return str(value).replace("\\", "\\\\").replace('"', '\\"')


def _write_hook(path: Path, body: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    # LF, not CRLF: git for Windows refuses a CRLF shebang line ("bad interpreter").
    path.write_bytes(body.replace("\r\n", "\n").encode("utf-8"))
    path.chmod(path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)


def install_hooks(workspace: Path, warn_only: bool = False) -> dict:
    gate = GATE_SCRIPT
    if not gate.is_file():
        return {
            "status": "error",
            "errors": [f"gate script not found next to the installer: {gate}"],
        }
    hooks = _hooks_dir(workspace)
    # Only the commit-msg gate is ever downgraded: pre-commit is advisory
    # unconditionally (see the module docstring for why).
    extra = " --warn-only" if warn_only else ""
    fields = {
        "marker": HOOK_MARKER,
        "python": _sh_escape(sys.executable),
        "gate": _sh_escape(gate),
        "workspace": _sh_escape(workspace.resolve()),
        "extra": extra,
    }

    written = []
    for name, template in (("pre-commit", PRE_COMMIT_BODY), ("commit-msg", COMMIT_MSG_BODY)):
        target = hooks / name
        if target.exists():
            existing = target.read_text(encoding="utf-8", errors="replace")
            if HOOK_MARKER not in existing:
                # Someone else's hook. Refuse rather than silently destroy it.
                return {
                    "status": "conflict",
                    "errors": [
                        f"{target} exists and was not created by the intent gate; "
                        "merge it by hand, or move it aside and re-run"
                    ],
                    "hooks_dir": str(hooks),
                }
        _write_hook(target, template.format(**fields))
        written.append(str(target))

    return {
        "status": "installed",
        "hooks_dir": str(hooks),
        "hooks": written,
        "gate": str(gate),
        "workspace": str(workspace.resolve()),
        "warn_only": warn_only,
        "replay": (
            f'"{sys.executable}" "{gate}" --install-hooks '
            f'--workspace "{workspace.resolve()}"' + extra
        ),
    }


def uninstall_hooks(workspace: Path) -> dict:
    hooks = _hooks_dir(workspace)
    removed, kept = [], []
    for name in ("pre-commit", "commit-msg"):
        target = hooks / name
        if not target.exists():
            continue
        text = target.read_text(encoding="utf-8", errors="replace")
        if HOOK_MARKER in text:
            target.unlink()
            removed.append(str(target))
        else:
            kept.append(str(target))
    return {"status": "uninstalled", "removed": removed, "kept_foreign_hooks": kept}
